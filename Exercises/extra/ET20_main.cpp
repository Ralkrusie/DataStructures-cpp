/*
20. 顺序表逆置
顺序表逆置
一、问题描述
给定一个整数数组，将其原地逆置，即第i个元素与第n-i+1个元素交换位置（1 ≤ i ≤ n/2）。要求空间复杂度为O(1)。

二、输入形式
第一行输入一个正整数n（1 ≤ n ≤ 100000），表示数组长度。
第二行输入n个整数，表示数组元素。

三、输出形式
输出逆置后的数组，元素之间用空格分隔。

四、样例输入

5
1 2 3 4 5
五、样例输出

5 4 3 2 1
六、样例说明
原数组：[1, 2, 3, 4, 5]
逆置过程：

交换位置1和5：1↔5 → [5, 2, 3, 4, 1]

交换位置2和4：2↔4 → [5, 4, 3, 2, 1]

位置3是中间元素，无需交换

逆置后：[5, 4, 3, 2, 1]

七、评分标准
共6个测试用例。

八、类库使用要求
可以使用基本输入输出，数组或vector。禁止使用reverse函数。
*/
#include <iostream>
#include <vector>

int main() {
    int n;
    std::cin >> n;

    std::vector<int> a(n);
    for (int i = 0; i < n; ++i) {
        std::cin >> a[i];
    }

    for (int i = 0, j = n - 1; i < j; ++i, --j) {
        int t = a[i];
        a[i] = a[j];
        a[j] = t;
    }

    for (int i = 0; i < n; ++i) {
        if (i > 0) {
            std::cout << ' ';
        }
        std::cout << a[i];
    }
    std::cout << '\n';
    return 0;
}